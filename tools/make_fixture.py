"""Write the synthetic companyfacts and submissions fixtures to examples/fixtures/v1/.

Usage: python tools/make_fixture.py [--seed 42] [--out examples/fixtures/v1]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from sec_business_evidence.synthetic import (  # noqa: E402
    DEFAULT_SEED, FIXTURE_VERSION, ISSUERS, build_companyfacts, build_submissions,
)

FIXTURE_MD = """# Fixture v1

Authored synthetic demonstration data. Fictional identifiers. Not derived from any person,
company, account or dataset. Generated by `tools/make_fixture.py` seed `{seed}`, version v1.

Three fictional issuers with CIKs in the 9999999xxx range, which no real registrant uses:

| File | Issuer | Notes |
|---|---|---|
| `CIK9999999001_companyfacts.json` | Northwind Demo Corp | 10-K/A filed 2025-03-15 restates FY2023 revenue and net income |
| `CIK9999999002_companyfacts.json` | Bluewater Demo Holdings | FY2021 operating cash flow omitted; no DebtCurrent tag |
| `CIK9999999003_companyfacts.json` | Granite Demo Industries | revenue decline and receivables build-up in FY2024 |

Each `*_submissions.json` lists that issuer's filings in the submissions API shape.
Every 10-K repeats the prior year as a comparative (same value, different accession), which
exercises deduplication. Three 10-Q filings per year carry quarterly durations, which must
never be compared with annual durations. `dei:EntityCommonStockSharesOutstanding` is
reported in `shares`, which the money ratios must ignore.

Values are whole US dollars stored as JSON integers. The URLs the pipeline builds from these
accessions are well formed but do not resolve on sec.gov because the issuers are fictional.

`manifest.json` records the sha256 of every file for the run manifest.
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--out", type=Path, default=ROOT / "examples" / "fixtures" / FIXTURE_VERSION)
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    manifest: dict[str, str] = {}
    for spec in ISSUERS:
        doc, filings = build_companyfacts(spec, seed=args.seed)
        subs = build_submissions(spec, filings)
        for name, payload in ((f"CIK{spec.cik:010d}_companyfacts.json", doc), (f"CIK{spec.cik:010d}_submissions.json", subs)):
            text = json.dumps(payload, indent=1, sort_keys=True)
            (args.out / name).write_text(text + "\n", encoding="utf-8")
            manifest[name] = hashlib.sha256(text.encode("utf-8")).hexdigest()
    (args.out / "manifest.json").write_text(json.dumps({"version": FIXTURE_VERSION, "seed": args.seed, "sha256": manifest}, indent=1) + "\n", encoding="utf-8")
    (args.out / "FIXTURE.md").write_text(FIXTURE_MD.format(seed=args.seed), encoding="utf-8")
    print(f"wrote {len(manifest)} fixture files to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
